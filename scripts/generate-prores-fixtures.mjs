/**
 * Generate the packaged ProRes media fixtures and their integrity manifest.
 *
 * `engine/self_test.py` is the gate the Windows installer runs against the
 * *exact* packaged Python/OpenCV/FFmpeg runtime before it commits an install.
 * It decodes two real ProRes files and refuses to continue unless the bundled
 * FFmpeg reports ProRes 422 Standard and ProRes 422 HQ. Those two files used to
 * exist only inside a package build — `package-windows.mjs` synthesised them
 * into the staging tree with whatever `ffmpeg` happened to be on the build
 * machine — so the same gate could never be run from a source checkout, and the
 * bytes that shipped depended on who built the release.
 *
 * The fixtures now live in the source tree, are generated by this script alone,
 * and carry a manifest recording exactly what they are. Packaging copies them
 * rather than re-synthesising them, so the payload is reproducible.
 *
 * Usage:
 *   node scripts/generate-prores-fixtures.mjs           regenerate + rewrite manifest
 *   node scripts/generate-prores-fixtures.mjs --check   verify, write nothing
 */

import assert from "node:assert/strict";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
export const FIXTURE_DIR = path.join(root, "engine", "fixtures");
export const MANIFEST_FILE = path.join(FIXTURE_DIR, "manifest.json");

/**
 * The synthesis recipe. Kept byte-identical to the command `package-windows.mjs`
 * used before it started copying these files, so an existing release payload and
 * a freshly generated fixture are the same media.
 *
 * `testsrc2` is deliberate: it is animated and high-detail, so the clip analyser
 * sees real motion and a populated histogram rather than the degenerate values a
 * flat colour bar would produce. One second at 23.976 fps is the shortest clip
 * that still yields the three sampled frames `test-prores-fixtures.py` requires.
 */
export const RECIPE = {
  source: "testsrc2=size=320x180:rate=24000/1001",
  durationSeconds: "1",
  encoder: "prores_ks",
  pixelFormat: "yuv422p10le",
  width: 320,
  height: 180,
};

/**
 * `-profile:v` values for `prores_ks` and the profile name FFprobe reports back.
 * `self_test.py` substring-matches the lowercased name, which is why the
 * expected string is asserted here rather than assumed.
 */
export const FIXTURES = [
  { file: "prores-422-standard.mov", profileArg: "2", expectedProfile: "Standard" },
  { file: "prores-422-hq.mov", profileArg: "3", expectedProfile: "HQ" },
];

function resolveTool(tool) {
  const override = (process.env[`FLAGSHIPEDITOR_${tool.toUpperCase()}`] || "").trim();
  if (override) return override;
  return tool;
}

function sha256(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function probe(ffprobe, file) {
  const raw = execFileSync(ffprobe, [
    "-v", "error",
    "-select_streams", "v:0",
    "-show_entries", "stream=codec_name,profile,width,height,pix_fmt",
    "-show_entries", "format=duration",
    "-of", "json", file,
  ], { encoding: "utf8" });
  const parsed = JSON.parse(raw);
  const stream = (parsed.streams || [])[0];
  if (!stream) throw new Error(`FFprobe reported no video stream in ${path.basename(file)}`);
  return {
    codec: String(stream.codec_name),
    profile: String(stream.profile),
    width: Number(stream.width),
    height: Number(stream.height),
    pixelFormat: String(stream.pix_fmt),
    durationSeconds: Number(Number(parsed.format.duration).toFixed(3)),
  };
}

/** Assert a probed fixture is the media the self-test contract requires. */
export function assertContract(spec, probed) {
  assert.equal(probed.codec, "prores", `${spec.file}: codec is ${probed.codec}, not prores`);
  assert.equal(
    probed.profile, spec.expectedProfile,
    `${spec.file}: FFprobe reports profile "${probed.profile}", not "${spec.expectedProfile}"`,
  );
  // self_test.py lowercases and substring-matches, so guard the exact property
  // it relies on rather than only the name above.
  const token = spec.file.includes("-hq") ? "hq" : "standard";
  assert.ok(
    probed.profile.toLowerCase().includes(token),
    `${spec.file}: self_test.py looks for "${token}" inside profile "${probed.profile}"`,
  );
  assert.equal(probed.width, RECIPE.width, `${spec.file}: width is ${probed.width}`);
  assert.equal(probed.height, RECIPE.height, `${spec.file}: height is ${probed.height}`);
  assert.equal(
    probed.pixelFormat, RECIPE.pixelFormat,
    `${spec.file}: pixel format is ${probed.pixelFormat}, not 10-bit 4:2:2`,
  );
  assert.ok(
    probed.durationSeconds >= 0.9 && probed.durationSeconds <= 1.1,
    `${spec.file}: duration ${probed.durationSeconds}s is outside the 1 s contract`,
  );
}

function generate(ffmpeg, spec) {
  const destination = path.join(FIXTURE_DIR, spec.file);
  execFileSync(ffmpeg, [
    "-v", "error",
    "-f", "lavfi", "-i", RECIPE.source,
    "-t", RECIPE.durationSeconds,
    "-c:v", RECIPE.encoder,
    "-profile:v", spec.profileArg,
    "-pix_fmt", RECIPE.pixelFormat,
    "-y", destination,
  ]);
  return destination;
}

function toolVersion(tool) {
  const banner = execFileSync(tool, ["-version"], { encoding: "utf8" }).split("\n")[0];
  return banner.trim();
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const ffmpeg = resolveTool("ffmpeg");
  const ffprobe = resolveTool("ffprobe");

  if (checkOnly) {
    if (!fs.existsSync(MANIFEST_FILE)) {
      throw new Error(
        `Fixture manifest is missing: ${MANIFEST_FILE}. Run "npm run generate:fixtures".`,
      );
    }
    const manifest = JSON.parse(fs.readFileSync(MANIFEST_FILE, "utf8"));
    for (const spec of FIXTURES) {
      const destination = path.join(FIXTURE_DIR, spec.file);
      if (!fs.existsSync(destination)) {
        throw new Error(`Packaged media fixture is missing: ${spec.file}`);
      }
      const recorded = (manifest.fixtures || []).find((entry) => entry.file === spec.file);
      if (!recorded) throw new Error(`Fixture manifest has no entry for ${spec.file}`);
      const bytes = fs.statSync(destination).size;
      assert.equal(bytes, recorded.bytes, `${spec.file}: ${bytes} bytes, manifest says ${recorded.bytes}`);
      assert.equal(sha256(destination), recorded.sha256, `${spec.file}: sha256 does not match the manifest`);
      assertContract(spec, probe(ffprobe, destination));
    }
    console.log(`ProRes fixtures verified against the manifest (${FIXTURES.length} files).`);
    return;
  }

  fs.mkdirSync(FIXTURE_DIR, { recursive: true });
  const entries = [];
  for (const spec of FIXTURES) {
    const destination = generate(ffmpeg, spec);
    const probed = probe(ffprobe, destination);
    assertContract(spec, probed);
    entries.push({
      file: spec.file,
      profileArg: spec.profileArg,
      codec: probed.codec,
      profile: probed.profile,
      width: probed.width,
      height: probed.height,
      pixelFormat: probed.pixelFormat,
      durationSeconds: probed.durationSeconds,
      bytes: fs.statSync(destination).size,
      sha256: sha256(destination),
    });
  }

  const manifest = {
    // Regenerating on a different FFmpeg build changes the bytes, so the hashes
    // and the version that produced them are written together and are only ever
    // compared against each other.
    generatedWith: toolVersion(ffmpeg),
    recipe: RECIPE,
    fixtures: entries,
  };
  fs.writeFileSync(MANIFEST_FILE, `${JSON.stringify(manifest, null, 2)}\n`);
  for (const entry of entries) {
    console.log(`  ${entry.file}  ${entry.profile}  ${entry.width}x${entry.height}  ${entry.bytes} bytes`);
  }
  console.log(`ProRes fixtures written to engine/fixtures with ${MANIFEST_FILE.split(path.sep).pop()}.`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (error) {
    console.error(`ProRes fixture generation failed: ${error.message}`);
    process.exit(1);
  }
}
